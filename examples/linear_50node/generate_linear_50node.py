"""Seeded generator for the 50-node linear consensus example.

Writes examples/linear_50node/linear_50node_topology.py. Unlike the IEEE
30-bus case, both this generator and its output are committed -- the
generator is our own code and seeded, so there's no copyright or
reproducibility reason to hide it. See
docs/example_linear_50node_spec.md sections 2-3 for the full spec.

Usage:
    python examples/linear_50node/generate_linear_50node.py [seed] [n_faults]

Defaults: seed=0, n_faults=7.
"""

import sys
from pathlib import Path

import networkx as nx
import numpy as np

HERE = Path(__file__).parent
OUTPUT_PATH = HERE / "linear_50node_topology.py"

N_NODES = 50
PLANE_SIZE = 10.0
EDGE_RADIUS = 2.0
DEFAULT_SEED = 0
DEFAULT_N_FAULTS = 7


def _canon(edge):
    i, j = edge
    return (i, j) if i < j else (j, i)


def _draw_positions_and_edges(rng):
    nodes = list(range(1, N_NODES + 1))
    positions = {
        node: tuple(float(c) for c in rng.uniform(0.0, PLANE_SIZE, size=2))
        for node in nodes
    }

    edges = set()
    for a in range(len(nodes)):
        for b in range(a + 1, len(nodes)):
            i, j = nodes[a], nodes[b]
            xi, yi = positions[i]
            xj, yj = positions[j]
            distance = ((xi - xj) ** 2 + (yi - yj) ** 2) ** 0.5
            if distance <= EDGE_RADIUS:
                edges.add(_canon((i, j)))

    return nodes, positions, sorted(edges)


def _generate_connected(seed):
    """Draw positions/edges for `seed`; if the resulting graph isn't
    connected, increment the seed and redraw from scratch, repeating
    until connected. Returns (successful_seed, rng, nodes, positions,
    edges) -- `rng` is left mid-stream so weight generation (step 4)
    continues drawing from the SAME seeded stream, keeping "all
    randomness flows from one seed" true for the whole generation.
    """
    candidate_seed = seed
    while True:
        rng = np.random.default_rng(candidate_seed)
        nodes, positions, edges = _draw_positions_and_edges(rng)

        graph = nx.Graph()
        graph.add_nodes_from(nodes)
        graph.add_edges_from(edges)

        if nx.is_connected(graph):
            return candidate_seed, rng, nodes, positions, edges

        candidate_seed += 1


def generate(seed, n_faults):
    successful_seed, rng, nodes, positions, edges = _generate_connected(seed)

    node_weights = {node: float(rng.uniform(1.0, 5.0)) for node in nodes}
    edge_weights = {edge: float(rng.uniform(1.0, 10.0)) for edge in edges}

    neighbors = {node: set() for node in nodes}
    for u, v in edges:
        neighbors[u].add(v)
        neighbors[v].add(u)

    faulty_nodes = nodes[:n_faults]
    for node in faulty_nodes:
        full_coupling = sum(
            edge_weights[_canon((node, j))] for j in neighbors[node]
        )
        node_weights[node] = -full_coupling - 1.0

    return {
        "seed": successful_seed,
        "nodes": nodes,
        "edges": edges,
        "node_weights": node_weights,
        "edge_weights": edge_weights,
        "positions": positions,
        "faulty_nodes": faulty_nodes,
    }


def write_topology(result, n_faults, output_path):
    seed = result["seed"]
    content = (
        "# 50-node linear consensus example, randomly generated (seeded).\n"
        f"# Generated by generate_linear_50node.py, seed={seed}, "
        f"n_faults={n_faults}.\n"
        '"""50-node linear consensus topology, randomly generated (seeded).\n'
        "\n"
        "Positions are drawn uniformly on a 10x10 plane; an edge connects\n"
        "every pair of nodes within Euclidean distance 2. The seed recorded\n"
        "here is the one that produced a connected graph (see\n"
        "generate_linear_50node.py's connectivity-retry loop). Weights are\n"
        "part of the artifact, not just the topology -- this case is not\n"
        "reproducible from NODES/EDGES alone. Both this module and its\n"
        "generator are committed; re-run the generator to reproduce or vary\n"
        "the seed/n_faults instead of hand-editing this file.\n"
        '"""\n'
        "\n"
        f"NODES = {result['nodes']!r}\n"
        "\n"
        f"EDGES = {result['edges']!r}\n"
        "\n"
        f"NODE_WEIGHTS = {result['node_weights']!r}\n"
        "\n"
        f"EDGE_WEIGHTS = {result['edge_weights']!r}\n"
        "\n"
        f"POSITIONS = {result['positions']!r}\n"
    )
    Path(output_path).write_text(content)


def main():
    seed = int(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SEED
    n_faults = int(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_N_FAULTS

    result = generate(seed, n_faults)
    write_topology(result, n_faults, OUTPUT_PATH)

    graph = nx.Graph()
    graph.add_nodes_from(result["nodes"])
    graph.add_edges_from(result["edges"])

    print(f"Wrote {OUTPUT_PATH}")
    print(f"Successful seed: {result['seed']}")
    print(f"Nodes: {len(result['nodes'])}")
    print(f"Edges: {len(result['edges'])}")
    print(f"Connected: {nx.is_connected(graph)}")
    print(f"Faulty nodes: {result['faulty_nodes']}")


if __name__ == "__main__":
    main()
